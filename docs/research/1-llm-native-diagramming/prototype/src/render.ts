// Renderizador SVG determinista: misma geometría => mismos bytes.
import type { Layout, LNode, LEdge, P } from './layout.ts';
import { THEMES, TYPE, type Theme } from './theme.ts';
import { FONT_FAMILY, woff2Base64 } from './fonts.ts';

const esc = (s: string) => s.replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;').replace(/"/g, '&quot;');
const f = (n: number) => (Math.round(n * 10) / 10).toString();

function textLines(lines: string[], cx: number, top: number, size: number, weight: number, lh: number, color: string, anchor = 'middle'): string {
  return lines.map((l, i) => `<text x="${f(cx)}" y="${f(top + i * lh + lh / 2 + size * 0.35)}" font-size="${size}" font-weight="${weight}" fill="${color}" text-anchor="${anchor}">${esc(l)}</text>`).join('');
}

function roundedPath(pts: P[], r = 6): string {
  if (pts.length < 2) return '';
  let d = `M${f(pts[0][0])},${f(pts[0][1])}`;
  for (let i = 1; i < pts.length - 1; i++) {
    const [a, b, c] = [pts[i - 1], pts[i], pts[i + 1]];
    const l1 = Math.hypot(b[0] - a[0], b[1] - a[1]), l2 = Math.hypot(c[0] - b[0], c[1] - b[1]);
    const rr = Math.min(r, l1 / 2, l2 / 2);
    const p1: P = [b[0] + ((a[0] - b[0]) / l1) * rr, b[1] + ((a[1] - b[1]) / l1) * rr];
    const p2: P = [b[0] + ((c[0] - b[0]) / l2) * rr, b[1] + ((c[1] - b[1]) / l2) * rr];
    d += ` L${f(p1[0])},${f(p1[1])} Q${f(b[0])},${f(b[1])} ${f(p2[0])},${f(p2[1])}`;
  }
  const e = pts[pts.length - 1];
  return d + ` L${f(e[0])},${f(e[1])}`;
}

function smoothPath(pts: P[]): string {
  if (pts.length < 3) return roundedPath(pts, 0);
  let d = `M${f(pts[0][0])},${f(pts[0][1])}`;
  for (let i = 0; i < pts.length - 1; i++) {
    const p0 = pts[i - 1] ?? pts[i], p1 = pts[i], p2 = pts[i + 1], p3 = pts[i + 2] ?? p2;
    const c1: P = [p1[0] + (p2[0] - p0[0]) / 6, p1[1] + (p2[1] - p0[1]) / 6];
    const c2: P = [p2[0] - (p3[0] - p1[0]) / 6, p2[1] - (p3[1] - p1[1]) / 6];
    d += ` C${f(c1[0])},${f(c1[1])} ${f(c2[0])},${f(c2[1])} ${f(p2[0])},${f(p2[1])}`;
  }
  return d;
}

function shapeSvg(n: LNode, th: Theme): string {
  const t = th.roles[n.role];
  const dash = n.kind === 'external' ? ' stroke-dasharray="5 3"' : '';
  const common = `fill="${t.fill}" stroke="${t.stroke}" stroke-width="1.5"${dash}`;
  const { x, y, w, h } = n;
  switch (n.shape) {
    case 'pill': return `<rect x="${f(x)}" y="${f(y)}" width="${f(w)}" height="${f(h)}" rx="${f(h / 2)}" ${common}/>`;
    case 'diamond': return `<polygon points="${f(x + w / 2)},${f(y)} ${f(x + w)},${f(y + h / 2)} ${f(x + w / 2)},${f(y + h)} ${f(x)},${f(y + h / 2)}" ${common}/>`;
    case 'hexagon': return `<polygon points="${f(x + 14)},${f(y)} ${f(x + w - 14)},${f(y)} ${f(x + w)},${f(y + h / 2)} ${f(x + w - 14)},${f(y + h)} ${f(x + 14)},${f(y + h)} ${f(x)},${f(y + h / 2)}" ${common}/>`;
    case 'parallelogram': return `<polygon points="${f(x + 12)},${f(y)} ${f(x + w)},${f(y)} ${f(x + w - 12)},${f(y + h)} ${f(x)},${f(y + h)}" ${common}/>`;
    case 'cylinder': {
      const ry = 7;
      return `<path d="M${f(x)},${f(y + ry)} A${f(w / 2)},${ry} 0 0 1 ${f(x + w)},${f(y + ry)} V${f(y + h - ry)} A${f(w / 2)},${ry} 0 0 1 ${f(x)},${f(y + h - ry)} Z" ${common}/><path d="M${f(x)},${f(y + ry)} A${f(w / 2)},${ry} 0 0 0 ${f(x + w)},${f(y + ry)}" fill="none" stroke="${t.stroke}" stroke-width="1.5"/>`;
    }
    case 'pipe': {
      const rx = 9;
      return `<path d="M${f(x + rx)},${f(y)} H${f(x + w - rx)} A${rx},${f(h / 2)} 0 0 1 ${f(x + w - rx)},${f(y + h)} H${f(x + rx)} A${rx},${f(h / 2)} 0 0 1 ${f(x + rx)},${f(y)} Z" ${common}/><path d="M${f(x + w - rx)},${f(y)} A${rx},${f(h / 2)} 0 0 0 ${f(x + w - rx)},${f(y + h)}" fill="none" stroke="${t.stroke}" stroke-width="1.5"/>`;
    }
    case 'person': {
      return `<rect x="${f(x)}" y="${f(y + 16)}" width="${f(w)}" height="${f(h - 16)}" rx="14" ${common}/><circle cx="${f(x + w / 2)}" cy="${f(y + 13)}" r="12" ${common}/>`;
    }
    default: return `<rect x="${f(x)}" y="${f(y)}" width="${f(w)}" height="${f(h)}" rx="8" ${common}/>`;
  }
}

export type RenderOptions = { embedFont?: boolean; theme?: string; background?: boolean };

export function renderSvg(L: Layout, opts: RenderOptions = {}): string {
  const th = THEMES[opts.theme ?? L.theme] ?? THEMES.light;
  const out: string[] = [];
  const title = L.title ?? 'Diagram';
  out.push(`<svg xmlns="http://www.w3.org/2000/svg" width="${f(L.width)}" height="${f(L.height)}" viewBox="0 0 ${f(L.width)} ${f(L.height)}" role="img" aria-labelledby="t d" font-family="'${FONT_FAMILY}', Inter, 'Segoe UI', Helvetica, Arial, sans-serif">`);
  out.push(`<title id="t">${esc(title)}</title><desc id="d">${esc(`${L.nodes.filter((n) => !n.group).length} elements, ${L.edges.length} relationships. Generated by plano (${L.engine}).`)}</desc>`);
  out.push('<defs>');
  if (opts.embedFont !== false) {
    out.push(`<style>@font-face{font-family:'${FONT_FAMILY}';font-weight:400;src:url(data:font/woff2;base64,${woff2Base64(400)}) format('woff2')}@font-face{font-family:'${FONT_FAMILY}';font-weight:600;src:url(data:font/woff2;base64,${woff2Base64(600)}) format('woff2')}</style>`);
  }
  out.push(`<marker id="arrow" viewBox="0 0 10 10" refX="9.5" refY="5" markerWidth="11" markerHeight="11" markerUnits="userSpaceOnUse" orient="auto-start-reverse"><path d="M0,0.8 L10,5 L0,9.2 z" fill="${th.edge}"/></marker>`);
  out.push(`<marker id="arrow-open" viewBox="0 0 10 10" refX="9.5" refY="5" markerWidth="11" markerHeight="11" markerUnits="userSpaceOnUse" orient="auto-start-reverse"><path d="M0.5,0.8 L9.5,5 L0.5,9.2" fill="none" stroke="${th.edge}" stroke-width="1.4"/></marker>`);
  out.push('</defs>');
  if (opts.background !== false) out.push(`<rect width="100%" height="100%" fill="${th.canvas}"/>`);
  if (L.title) out.push(textLines([L.title], 24, 14, 16, 600, 22, th.text, 'start'));

  // grupos (de exterior a interior)
  for (const g of [...L.nodes].filter((n) => n.group).sort((a, b) => a.depth - b.depth)) {
    const solid = g.kind === 'zone' || g.kind === 'cluster' || g.kind === 'layer';
    out.push(`<g data-id="${esc(g.id)}" class="group"><title>${esc(g.blocks[0]?.lines.join(' ') ?? g.id)}</title><rect x="${f(g.x)}" y="${f(g.y)}" width="${f(g.w)}" height="${f(g.h)}" rx="10" fill="${th.groupFill[g.kind] ?? th.groupFill.group}" stroke="${th.groupStroke}" stroke-width="1.2"${solid ? '' : ' stroke-dasharray="6 4"'}/>`);
    for (const b of g.blocks) out.push(textLines(b.lines, g.x + g.content.x, g.y + g.content.y + b.y, b.style.size, b.style.weight, b.style.lineHeight, b.color === 'text' ? th.groupText : th.textMuted, 'start'));
    out.push('</g>');
  }
  for (const l of L.lifelines ?? []) out.push(`<line x1="${f(l.x)}" y1="${f(l.y1)}" x2="${f(l.x)}" y2="${f(l.y2)}" stroke="${th.groupStroke}" stroke-width="1.2" stroke-dasharray="4 4"/>`);
  // conectores
  for (const e of L.edges) {
    const dash = e.style === 'async' || e.style === 'reply' || e.style === 'dep' ? ' stroke-dasharray="5 4"' : '';
    const marker = e.dir === 'none' ? '' : e.style === 'dep' ? ' marker-end="url(#arrow-open)"' : ' marker-end="url(#arrow)"';
    const start = e.dir === 'both' ? ' marker-start="url(#arrow)"' : '';
    out.push(`<path data-id="${esc(e.id)}" d="${e.curved ? smoothPath(e.points) : roundedPath(e.points)}" fill="none" stroke="${th.edge}" stroke-width="1.4"${dash}${marker}${start}/>`);
  }
  // nodos
  for (const n of L.nodes.filter((x) => !x.group)) {
    const t = th.roles[n.role];
    out.push(`<g data-id="${esc(n.id)}" class="node ${esc(n.kind)}"><title>${esc(n.blocks.map((b) => b.lines.join(' ')).join(' — '))}</title>${shapeSvg(n, th)}`);
    const cx = n.x + n.content.x + n.content.w / 2;
    for (const b of n.blocks) out.push(textLines(b.lines, cx, n.y + n.content.y + b.y, b.style.size, b.style.weight, b.style.lineHeight, b.color === 'text' ? t.text : t.sub));
    out.push('</g>');
  }
  // etiquetas de conectores (encima de todo, con halo de fondo)
  for (const e of L.edges) {
    if (!e.label) continue;
    const l = e.label;
    // halo del color del fondo real: el del grupo más interno que contiene la etiqueta, o el lienzo
    const cx = l.x + l.w / 2, cy = l.y + l.h / 2;
    const host = L.nodes.filter((g) => g.group && cx > g.x && cx < g.x + g.w && cy > g.y && cy < g.y + g.h).sort((a, b) => b.depth - a.depth)[0];
    const bg = host ? th.groupFill[host.kind] ?? th.groupFill.group : th.edgeLabelBg;
    out.push(`<g class="edge-label" data-for="${esc(e.id)}"><rect x="${f(l.x)}" y="${f(l.y)}" width="${f(l.w)}" height="${f(l.h)}" rx="3" fill="${bg}" fill-opacity="0.94"/>`);
    out.push(textLines(l.lines, l.x + l.w / 2, l.y + 2, TYPE.edge.size, 400, TYPE.edge.lineHeight, th.textMuted));
    out.push('</g>');
  }
  out.push('</svg>');
  return out.join('');
}
